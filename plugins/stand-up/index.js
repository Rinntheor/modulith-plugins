// plugins/stand-up/index.js
//
// ============================================================
// 这个文件**故意什么都不做**，但它不能不存在
// ============================================================
//
// 本仓库的清单校验要求每个插件都有 `main` 与 `index.js`（`scripts/manifest.ts`
// 的 `REQUIRED_FILES`），因此这个占位文件是**格式要求**，不是这个插件的入口。
//
// 真正的入口是 `background.js` —— 它由宿主按清单里的 `contributes.background`
// 拉起在**一个独立的 Node 进程**里，与这个文件没有任何关系。
//
// 为什么这里不做点什么（例如注册一个命令）：那会让应用在启动时把这个插件的代码
// 载进**宿主自己的上下文**里，而这件事对这个插件毫无必要 —— 它没有界面、没有
// 命令、没有模块。无界面插件的意义正是"不必为了做一件小事而在宿主里留一份代码"。
//
// 因此：这里保持空。如果将来要给这个插件加一个"立即提醒一次"的命令，那正确的位置
// 是 `contributes.commands` + `contributes.background.events: ["onCommand:…"]`，
// 由**后台进程**处理，仍然不需要这个文件做事。
//
// 宿主不会加载它：`runtime: "sandboxed"` 的插件不走 in-process 加载路径，
// 而没有 `contributes.modules` / `contributes.surfaces` 也就不会开出任何界面。
